export function getLocalizedScenario(scenario: Scenario | null, lang: Language = 'en'): Scenario | null {
  if (!scenario) return null;
  if (lang === 'en') return scenario;

  const overrides = SCENARIO_TRANSLATIONS[lang]?.[scenario.id];
  const conceptMap = CONCEPT_TRANSLATIONS[lang] || {};

  const translatedEthicalConcepts = (scenario.ethicalConcepts || []).map(
    (concept) => conceptMap[concept] || concept
  );

  if (!overrides) {
    return {
      ...scenario,
      ethicalConcepts: translatedEthicalConcepts
    };
  }

  return {
    ...scenario,
    title: overrides.title || scenario.title,
    category: overrides.category || scenario.category,
    summary: overrides.summary || scenario.summary,
    description: overrides.description || scenario.description,
    question: overrides.question || scenario.question,
    thinkEthicallyHint: overrides.thinkEthicallyHint || scenario.thinkEthicallyHint,
    ethicalConcepts: translatedEthicalConcepts,
    options: scenario.options.map((opt, i) => {
      const translatedOpt = overrides.options?.[i];
      if (!translatedOpt) return opt;
      return {
        ...opt,
        text: translatedOpt.text || opt.text,
        explanation: translatedOpt.explanation || opt.explanation,
        ethicalFeedback: translatedOpt.ethicalFeedback || opt.ethicalFeedback,
        legalFeedback: translatedOpt.legalFeedback || opt.legalFeedback
      };
    }),
    legalPerspective: {
      ...scenario.legalPerspective,
      title: overrides.legalPerspective?.title || scenario.legalPerspective.title,
      explanation: overrides.legalPerspective?.explanation || scenario.legalPerspective.explanation,
      statutes: overrides.legalPerspective?.statutes || scenario.legalPerspective.statutes
    },
    ethicalPerspective: {
      ...scenario.ethicalPerspective,
      title: overrides.ethicalPerspective?.title || scenario.ethicalPerspective.title,
      principles: overrides.ethicalPerspective?.principles || scenario.ethicalPerspective.principles,
      deepDive: overrides.ethicalPerspective?.deepDive || scenario.ethicalPerspective.deepDive
    }
  };
}
